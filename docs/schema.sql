USE bucketly;

-- ----------------------------------------------------------------------------
-- 1. Dreams Table
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dreams (
    id BIGINT NOT NULL AUTO_INCREMENT,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    category VARCHAR(100) NOT NULL,
    target_date VARCHAR(100),
    status VARCHAR(50) NOT NULL DEFAULT 'Not Started',
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 2. Memories Table (Memory Wall Milestone 1)
-- One-to-one relationship with dreams (each completed dream has at most one memory)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS memories (
    id BIGINT NOT NULL AUTO_INCREMENT,
    dream_id BIGINT NOT NULL,
    completed_date DATE NOT NULL,
    story TEXT,
    photo_path VARCHAR(255),
    original_filename VARCHAR(255),
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_memories_dream_id (dream_id),
    CONSTRAINT fk_memories_dream FOREIGN KEY (dream_id) REFERENCES dreams (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 3. Users Table (Milestone 2D Authentication & Identity)
-- Stores user credentials and profile details matching User.java
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id BIGINT NOT NULL AUTO_INCREMENT,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 4. Dream Ownership Migration (Milestone 2E Multi-User Isolation)
-- Adds nullable user_id, index, and foreign key with ON DELETE RESTRICT to link
-- dreams to authenticated user accounts while preserving legacy unowned records.
-- ----------------------------------------------------------------------------
-- Manual Execution Instructions:
-- Execute the following statements in MySQL Workbench or mysql CLI:
--
ALTER TABLE dreams ADD COLUMN user_id BIGINT NULL AFTER id;
ALTER TABLE dreams ADD INDEX idx_dreams_user_id (user_id);
ALTER TABLE dreams ADD CONSTRAINT fk_dreams_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;

